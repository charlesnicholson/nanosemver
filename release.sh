#!/usr/bin/env bash
# Builds the assets for a release tag; publishing them is the caller's job (see the
# release job in .github/workflows/ci.yml). nanosemver.h carries an @NSV_VERSION@
# placeholder, so nothing checked in goes stale and no commit ever bumps a version.
#
#   ./release.sh vX.Y.Z [out-dir]   write into out-dir (build/release):
#                                     nanosemver.h            stamped with the tag
#                                     nanosemver.c
#                                     nanosemver-vX.Y.Z.zip   every tracked file, same
#                                                             stamped header
#                                     release_notes.md        the assets, explained
#                                   and print "release" or "prerelease".
#   ./release.sh --check            fail unless the in-tree header is still unstamped
set -euo pipefail
cd "$(dirname "$0")"

placeholder='@NSV_VERSION@'
grep -q "$placeholder" nanosemver.h || {
  echo "release.sh: nanosemver.h has no $placeholder placeholder" >&2
  exit 1
}
if [[ "${1:-}" == "--check" ]]; then
  exit 0
fi

tag="${1:?usage: release.sh vX.Y.Z [out-dir] | --check}"
out="${2:-build/release}"
ver="${tag#v}"

# semver.org's suggested regex, in POSIX ERE.
num='(0|[1-9][0-9]*)'
pre='(0|[1-9][0-9]*|[0-9]*[a-zA-Z-][0-9a-zA-Z-]*)'
bld='[0-9a-zA-Z-]+'
re="^$num\.$num\.$num(-$pre(\.$pre)*)?(\+$bld(\.$bld)*)?$"
if [[ "$tag" != v* || ! "$ver" =~ $re ]]; then
  echo "release.sh: tag '$tag' is not v followed by a semver 2.0.0 version" >&2
  exit 1
fi

name="nanosemver-$tag"
zip_name="$name.zip"
rm -rf "$out"
mkdir -p "$out/$name"
sed "s/$placeholder/$tag/" nanosemver.h > "$out/nanosemver.h"
cp nanosemver.c "$out/nanosemver.c"

# Every tracked file, modes kept, with the stamped header in place of the original.
while IFS= read -r -d '' f; do
  if [[ -f "$f" ]]; then
    mkdir -p "$out/$name/$(dirname "$f")"
    cp -p "$f" "$out/$name/$f"
  fi
done < <(git ls-files -z)
cp "$out/nanosemver.h" "$out/$name/nanosemver.h"
(cd "$out" && zip -qr "$zip_name" "$name")
rm -rf "${out:?}/$name"

cat > "$out/release_notes.md" <<NOTES
\`nanosemver.h\` and \`nanosemver.c\`: the library, header stamped \`$tag\`.
\`$zip_name\`: full source and tests, same stamped header.

The autogenerated source archives below carry an unstamped header, prefer the assets above.
NOTES

# The core is digits and dots, so any '-' before the build metadata starts a pre-release.
core_pre="${ver%%+*}"
if [[ "$core_pre" == *-* ]]; then
  echo prerelease
else
  echo release
fi
